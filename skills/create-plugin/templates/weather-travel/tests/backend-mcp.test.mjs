import { createHash } from 'node:crypto';

const enabled = config.backend === 'mcp' || process.env.WEATHER_TEST_ALL_BACKENDS === '1';
test('official MCP connection exposes app metadata, resources, original receipts, and update subscriptions', {skip:!enabled}, async t => {
  const { createServer } = await import('../adapters/mcp/server.mjs');
  const { Client } = await import('@modelcontextprotocol/sdk/client/index.js');
  const { InMemoryTransport } = await import('@modelcontextprotocol/sdk/inMemory.js');
  const { ResourceUpdatedNotificationSchema } = await import('@modelcontextprotocol/sdk/types.js');
  const base=await mkdtemp(join(tmpdir(),'weather-mcp-')), workspaceRoot=join(base,'work');
  await mkdir(join(base,'dist','ui'),{recursive:true}); await mkdir(workspaceRoot);
  await writeFile(join(base,'dist','ui','panel.html'),'<!doctype html><title>Weather app</title>');
  const options={dataDir:join(base,'data'),sessionId:'mcp-session',workspaceRoot};
  const server=createServer({...options,rootPath:base,pollInterval:20});
  const client=new Client({name:'weather-test',version:'1.0.0'});
  const [a,b]=InMemoryTransport.createLinkedPair();
  t.after(async()=>{await client.close();await server.close();await rm(base,{recursive:true,force:true});});
  await server.connect(a); await client.connect(b);
  const tools=(await client.listTools()).tools;
  assert.deepEqual(tools.find(tool=>tool.name===names.SavePlanDraft)._meta.ui.visibility,['app']);
  assert.deepEqual(tools.find(tool=>tool.name===names.SetFavorite)._meta.ui.visibility,['app']);
  assert.deepEqual(tools.find(tool=>tool.name===names.ApplyPlanOperations)._meta.ui.visibility,['model','app']);
  assert.equal(tools.find(tool=>tool.name===names.GetForecast)._meta.ui.resourceUri,resourceUri);
  const resources=(await client.listResources()).resources;
  assert.ok(resources.some(r=>r.uri===planUri)); assert.ok(resources.some(r=>r.uri===`${config.name}://favorites`));
  assert.match((await client.readResource({uri:resourceUri})).contents[0].text,/Weather app/u);
  await client.subscribeResource({uri:planUri});
  const updates=[];client.setNotificationHandler(ResourceUpdatedNotificationSchema,n=>updates.push(n.params.uri));
  const saved=await client.callTool({name:names.SavePlanDraft,arguments:{documentId:'trip',expectedRevision:0,operationId:'save-mcp',title:'MCP trip',entries:[]}});
  assert.equal(saved.structuredContent.document.revision,1);
  assert.equal(JSON.parse(saved.content[0].text).saved,true);
  const original=await client.callTool({name:names.GetOperation,arguments:{operationId:'save-mcp'}});
  assert.deepEqual(original.structuredContent,saved.structuredContent);
  assert.equal(JSON.parse((await client.readResource({uri:planUri})).contents[0].text).document.title,'MCP trip');
  assert.ok(updates.includes(planUri));
  updates.length=0;
  const nativePeer=createService(options);
  await nativePeer.invoke('ApplyPlanOperations',{documentId:'trip',expectedRevision:1,operationId:'native-change',title:'External change',operations:[{type:'upsert',entry:{id:'e',date:'2026-10-23',title:'Visit',notes:''}}]});
  nativePeer.close();
  await new Promise((resolve,reject)=>{const started=Date.now();const timer=setInterval(()=>{if(updates.includes(planUri)){clearInterval(timer);resolve();}else if(Date.now()-started>1500){clearInterval(timer);reject(new Error('No resource refresh after another connection changed the trip'));}},10);});
});

test('stdio executable uses only explicit host bindings and returns the real saved receipt', {skip:!enabled}, async t => {
  const { Client }=await import('@modelcontextprotocol/sdk/client/index.js');
  const { StdioClientTransport }=await import('@modelcontextprotocol/sdk/client/stdio.js');
  const base=await mkdtemp(join(tmpdir(),'weather-stdio-')),workspaceRoot=join(base,'work');await mkdir(workspaceRoot);
  const nativePeer=createService({dataDir:join(base,'data'),sessionId:'stdio-session',workspaceRoot});
  await nativePeer.invoke('SavePlanDraft',{documentId:'trip',expectedRevision:0,operationId:'native-seed',title:'Shared native trip',entries:[]});
  const client=new Client({name:'stdio-test',version:'1'});
  const transport=new StdioClientTransport({command:process.execPath,args:[fileURLToPath(new URL('../adapters/mcp/server.mjs',import.meta.url))],cwd:base,env:{...process.env,VYKOR_WEATHER_DATA_DIR:join(base,'data'),VYKOR_WEATHER_SESSION:createHash('sha256').update('stdio-session').digest('hex'),VYKOR_WEATHER_WORKSPACE:workspaceRoot},stderr:'pipe'});
  t.after(async()=>{await client.close();nativePeer.close();await rm(base,{recursive:true,force:true});});
  await client.connect(transport);
  const result=await client.callTool({name:names.ReadPlan,arguments:{}});
  assert.equal(result.structuredContent.document.revision,1);
  assert.equal(result.structuredContent.document.title,'Shared native trip');
  const saved=await client.callTool({name:names.SavePlanDraft,arguments:{documentId:'trip',expectedRevision:1,operationId:'mcp-change',title:'Same session from MCP',entries:[]}});
  assert.equal(saved.structuredContent.saved,true);
  assert.equal((await nativePeer.readPlan()).document.title,'Same session from MCP');
  const bad=await client.callTool({name:names.SavePlanDraft,arguments:{documentId:'trip',expectedRevision:0,operationId:'bad',title:'Injected',entries:[],dataDir:base}});
  assert.equal(bad.isError,true); assert.equal(JSON.parse(bad.content[0].text).code,'invalid_input');
});
